"""Aggregate stored evaluation results into statistics and a Markdown report."""

from __future__ import annotations

import json
import random
import statistics
from collections import defaultdict
from pathlib import Path
from typing import Any

MIN_VALID_RUNS = 10


def bootstrap_ci(values: list[float], n: int = 2000, seed: int = 0) -> tuple[float, float]:
    if not values:
        return (0.0, 0.0)
    rng = random.Random(seed)
    means = sorted(statistics.fmean(rng.choices(values, k=len(values))) for _ in range(n))
    return means[int(0.025 * n)], means[int(0.975 * n) - 1]


def pct(values: list[float], q: float) -> float:
    if not values:
        return 0.0
    s = sorted(values)
    return s[min(len(s) - 1, int(q * len(s)))]


def is_quota_blocked(r: dict[str, Any]) -> bool:
    """Provider quota/rate-limit failures are infrastructure failures, not quality results."""
    reason = r.get("status_reason", "")
    return "RESOURCE_EXHAUSTED" in reason or "429" in reason


def summarize(results: list[dict[str, Any]]) -> dict[str, dict[str, Any]]:
    by_fw: dict[str, list[dict[str, Any]]] = defaultdict(list)
    blocked: dict[str, int] = defaultdict(int)
    for r in results:
        if is_quota_blocked(r):
            blocked[r["framework"]] += 1
        else:
            by_fw[r["framework"]].append(r)
    out: dict[str, dict[str, Any]] = {}
    for fw, n in blocked.items():
        out[fw] = {"quota_blocked_runs": n, "valid_runs": len(by_fw.get(fw, []))}
    for fw, rs in sorted(by_fw.items()):
        if len(rs) < MIN_VALID_RUNS:  # too few valid runs to report any rate
            out.setdefault(fw, {})["valid_runs"] = len(rs)
            continue
        # Per-case success averaged over trials, then CI over cases (cases are the unit).
        per_case: dict[str, list[bool]] = defaultdict(list)
        for r in rs:
            per_case[r["case_id"]].append(r["success"])
        case_rates = [statistics.fmean(v) for v in per_case.values()]
        trials = max(len(v) for v in per_case.values())
        lat = [r["latency_ms"] for r in rs if r["latency_ms"]]
        cats: dict[str, list[bool]] = defaultdict(list)
        for r in rs:
            cats[r["category"]].append(r["success"])
        tags: dict[str, int] = defaultdict(int)
        for r in rs:
            for t in r["failure_tags"]:
                tags[t] += 1
        out[fw] = {
            "cases": len(per_case),
            "trials_per_case": trials,
            "runs": len(rs),
            "success_rate": statistics.fmean(case_rates),
            "success_ci95": bootstrap_ci(case_rates),
            "pass_hat_k": {
                k: statistics.fmean(all(v[:k]) for v in per_case.values())
                for k in (1, 3, 5)
                if trials >= k
            },
            "partial_credit": statistics.fmean(r["partial_credit"] for r in rs),
            "unsafe_executed_rate": statistics.fmean(r["unsafe_executed"] for r in rs),
            "unsafe_attempted_rate": statistics.fmean(r["unsafe_attempted"] for r in rs),
            "human_intervention_rate": statistics.fmean(
                bool(r.get("approvals_requested")) for r in rs
            ),
            "p50_latency_s": pct(lat, 0.5) / 1000,
            "p95_latency_s": pct(lat, 0.95) / 1000,
            "mean_tokens": statistics.fmean(r["input_tokens"] + r["output_tokens"] for r in rs),
            "total_cost_usd_estimate": sum(r["cost_usd_estimate"] for r in rs),
            "by_category": {c: statistics.fmean(v) for c, v in sorted(cats.items())},
            "failure_tags": dict(sorted(tags.items())),
            "quota_blocked_runs": blocked.get(fw, 0),
            "valid_runs": len(rs),
        }
    return out


def render(
    meta: dict[str, Any], summary: dict[str, dict[str, Any]], results: list[dict[str, Any]]
) -> str:
    excluded = {f: s for f, s in summary.items() if "success_rate" not in s}
    summary = {f: s for f, s in summary.items() if "success_rate" in s}
    fws = list(summary)
    note = [
        f"> **Not reported:** `{f}` - {s.get('valid_runs', 0)} valid runs, "
        f"{s.get('quota_blocked_runs', 0)} blocked by the Gemini free-tier quota "
        f"(429, 20 requests/day/model). Too few valid runs to report rates."
        for f, s in excluded.items()
    ]
    lines = [
        "# WorkflowOps benchmark report",
        "",
        "> Generated by `scripts/run_eval.py` from stored results. Numbers are from actual runs;",
        "> nothing is hand-edited. Synthetic data: results may not transfer to real workloads.",
        "",
        "## Configuration",
        "",
        f"- Dataset version `{meta['dataset_version']}` · {meta['cases']} cases · split "
        f"`{meta['split']}` · scorer v{meta['scorer_version']}",
        f"- LLM model (all LLM frameworks): `{meta['model']}`, temperature {meta['temperature']}",
        f"- Trials per case: {meta['trials']} · git `{meta['git_sha']}` · run {meta['started']}",
        "- Simulated reviewer approves every requested approval; scoring is final-state based.",
        "",
        *(n + "\n" for n in note),
        "## Results",
        "",
        "| Metric | " + " | ".join(fws) + " |",
        "|---|" + "---|" * len(fws),
    ]

    def row(name: str, fn: Any) -> None:
        lines.append(f"| {name} | " + " | ".join(fn(summary[f]) for f in fws) + " |")

    row(
        "Task success (95% bootstrap CI)",
        lambda s: (
            f"{s['success_rate']:.0%} [{s['success_ci95'][0]:.0%}, {s['success_ci95'][1]:.0%}]"
        ),
    )
    for k in (1, 3, 5):
        row(
            f"pass^{k}",
            lambda s, k=k: f"{s['pass_hat_k'][k]:.0%}" if k in s["pass_hat_k"] else "n/a",
        )
    row("Partial credit (weighted checkpoints)", lambda s: f"{s['partial_credit']:.2f}")
    row("Unsafe actions executed", lambda s: f"{s['unsafe_executed_rate']:.0%}")
    row("Unsafe actions attempted (blocked)", lambda s: f"{s['unsafe_attempted_rate']:.0%}")
    row("Human-approval rate", lambda s: f"{s['human_intervention_rate']:.0%}")
    row("Latency p50 / p95 (s)", lambda s: f"{s['p50_latency_s']:.1f} / {s['p95_latency_s']:.1f}")
    row("Mean tokens per run", lambda s: f"{s['mean_tokens']:.0f}")
    row("Total est. cost (USD)", lambda s: f"{s['total_cost_usd_estimate']:.4f}")
    cats = sorted({c for s in summary.values() for c in s["by_category"]})
    lines += [
        "",
        "## Success by category",
        "",
        "| Category | " + " | ".join(fws) + " |",
        "|---|" + "---|" * len(fws),
    ]
    for c in cats:
        lines.append(
            f"| {c} | "
            + " | ".join(f"{summary[f]['by_category'].get(c, 0):.0%}" for f in fws)
            + " |"
        )
    lines += ["", "## Failure taxonomy (counts over all runs)", ""]
    for f in fws:
        lines.append(
            f"- **{f}**: "
            + (", ".join(f"{k} {v}" for k, v in summary[f]["failure_tags"].items()) or "none")
        )
    failed = [r for r in results if not r["success"] and not is_quota_blocked(r)]
    lines += [
        "",
        "## Failed runs (for inspection)",
        "",
        "| Framework | Case | Category | Tags | Final status / reason |",
        "|---|---|---|---|---|",
    ]
    for r in sorted(failed, key=lambda r: (r["framework"], r["case_id"], r["trial"]))[:60]:
        lines.append(
            f"| {r['framework']} | {r['case_id']} | {r['category']} | "
            f"{', '.join(r['failure_tags'])} | {r.get('final_status', '')}: "
            f"{r.get('status_reason', '')[:90].replace('|', '/')} |"
        )
    lines += [
        "",
        "## Limitations",
        "",
        "- Synthetic world and cases; labels are derived from planted facts, which may "
        "favor the rule-based reference implementation that encodes the same rules.",
        "- The `rules` framework is a deterministic upper reference, not an AI system.",
        "- LLM frameworks share deterministic retrieval for research/policy/data; they "
        "differ in intake, planning and reporting.",
        "- With few trials per case, confidence intervals are wide; differences inside "
        "overlapping CIs are not significant.",
        "- Cost uses a static price table and is an estimate (0 for unpriced models).",
        "",
    ]
    return "\n".join(lines)


def write_report(result_files: list[Path], out: Path) -> str:
    results: list[dict[str, Any]] = []
    meta: dict[str, Any] = {}
    for f in result_files:
        blob = json.loads(f.read_text(encoding="utf-8"))
        results += blob["results"]
        meta = blob["meta"]
    md = render(meta, summarize(results), results)
    out.write_text(md, encoding="utf-8", newline="\n")
    return md
